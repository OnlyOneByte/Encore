-- #766: media.guide_offset_ms — the measured signed millisecond offset of the vocals stem against
-- the instrumental, so guide/instrumental alignment is OBSERVABLE instead of assumed.
--
-- A real numbered migration (0006, after #425's 0005_tv_background_color), NOT an in-place edit of a
-- baseline: drizzle keys replay on the journal `when`, so a rewritten baseline never re-applies to an
-- existing box and the column would be missing at boot the first time a reader selected it (the trap
-- 0004/0005 headers record). This replays only on DBs that have not recorded idx:6.
--
-- ADDITIVE AND NULLABLE. A plain `ADD COLUMN`, not the __new_ create-copy-drop-rename idiom, because
-- `media` needs no primary-key change. The column is NULLABLE with no default on purpose: null ⇔ "never
-- measured / row predates the feature", which the client's guideOffsetSec() maps to 0 — so every song
-- already in the library keeps today's behaviour byte-for-byte after the upgrade, with no backfill.
-- (drizzle-kit also wanted to rebuild room_settings here, chasing a stale 0005 snapshot that predates
-- that migration's hand-written DROP COLUMN; that rebuild is unrelated to this change and is omitted.)
ALTER TABLE `media` ADD `guide_offset_ms` integer;
