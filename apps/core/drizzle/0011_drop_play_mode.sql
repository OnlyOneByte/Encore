-- Drop `media.play_mode`.
--
-- The column encoded two things at once: whether a song's ref was a playable FILE or a YouTube embed
-- id, and whether it had been cooked. Nothing plays unprocessed any more — the only thing the TV ever
-- loads is a separated instrumental — so the embed half is gone and the cooked half is already carried
-- by `stem_status` + `instrumental_ref`. Keeping the column would leave two sources of truth for
-- playability, which is exactly the shape of bug it used to cause (a row could read `file` while
-- having no `instrumental_ref`).
--
-- No data is lost that is not derivable: `play_mode = 'file' AND stem_status = 'ready'` was the old
-- playability test, and `stem_status = 'ready' AND instrumental_ref IS NOT NULL` is the new one. Rows
-- that were `file` only because they were mid-cook keep their `stem_status = 'queued'`.
--
-- Sidecars need no migration: `play_mode` was never persisted in one — sidecar.ts derived it on read.
ALTER TABLE `media` DROP COLUMN `play_mode`;
