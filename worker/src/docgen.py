"""Generate the pipeline documentation from the plans themselves.

    python -m src.docgen            # print the region
    python -m src.docgen --write    # rewrite it inside docs/ARCHITECTURE.md

WHY GENERATED. This repo has a demonstrated problem with architecture prose: `fetch.py`'s module
docstring stated that "both separation and alignment call" `resolve_source_audio` when three of its four
callers did not, and `STAGE_PLANS` declared two stages for an action with eight steps. A hand-written
description of the pipeline is a description that will be wrong, and nothing will notice.

So the tables below are computed from `PLANS`, written into `docs/ARCHITECTURE.md` between markers, and a
test asserts the committed file matches regeneration. Everything outside the markers stays hand-written —
the reasoning is a human's job; the inventory is not.

It lives in ARCHITECTURE.md rather than a new file because that is the one canonical system document,
and a reader looking for how the worker runs is already there.
"""

from __future__ import annotations

import sys
from pathlib import Path

from .plans import PLANS
from .runtime.plan import stages_of
from .vocabulary import Action

BEGIN = "<!-- BEGIN generated:worker-pipeline -->"
END = "<!-- END generated:worker-pipeline -->"


def _repo_root() -> Path:
    """The REPO root: the directory holding both `core/` and `worker/`.

    NOT `bunfig.toml` any more. That was the marker while the TypeScript project sat at the repo root, and
    it was chosen so both languages would agree by construction — but the JS project moved into `core/` and
    took its bunfig with it, so the walk found nothing above `worker/` and every test here died at import
    with `SystemExit`. Two directories is what actually defines this root, and neither package root can
    satisfy it by accident.
    """
    here = Path(__file__).resolve()
    for candidate in [here.parent, *here.parents]:
        if (candidate / "core").is_dir() and (candidate / "worker").is_dir():
            return candidate
    raise SystemExit(f"no directory with both core/ and worker/ above {here}")


ARCHITECTURE = _repo_root() / "docs" / "ARCHITECTURE.md"


def render() -> str:
    """The generated region, as markdown."""
    out: list[str] = [
        BEGIN,
        "",
        "<!-- Generated by `python -m src.docgen --write` from worker/src/plans.py.",
        "     Do not edit inside the markers; edit the plans. A test asserts this matches. -->",
        "",
        "Each action the core dispatches runs one flat plan of steps over a typed per-job context. The",
        "coarse `Stage` values are what the phone's progress bar reads; the step names are what",
        "`/metrics` times individually.",
        "",
    ]
    for action in Action:
        plan = PLANS.get(action)
        if plan is None:
            continue
        stages = " → ".join(s.value for s in stages_of(plan))
        out.append(f"**`{action.value}`** — stages: {stages}")
        out.append("")
        out.append("| # | step | stage | reads | writes |")
        out.append("|---|---|---|---|---|")
        for i, step in enumerate(plan.steps(), 1):
            reads = ", ".join(f"`{r}`" for r in sorted(step.reads)) or "—"
            writes = ", ".join(f"`{w}`" for w in sorted(step.writes)) or "—"
            out.append(f"| {i} | `{step.name}` | {step.stage.value} | {reads} | {writes} |")
        out.append("")

    out.append("```mermaid")
    out.append("flowchart LR")
    for action in Action:
        plan = PLANS.get(action)
        if plan is None:
            continue
        key = action.value.replace("-", "_")
        out.append(f"  subgraph {key}[{action.value}]")
        out.append("    direction LR")
        names = [s.name for s in plan.steps()]
        for i, name in enumerate(names):
            out.append(f'    {key}_{i}["{name}"]')
        for i in range(len(names) - 1):
            out.append(f"    {key}_{i} --> {key}_{i + 1}")
        out.append("  end")
    out.append("```")
    out.append("")
    out.append(END)
    return "\n".join(out)


def splice(existing: str, region: str) -> str:
    """Replace the marked region, or append it after section 7 if the markers are absent."""
    if BEGIN in existing and END in existing:
        head = existing.split(BEGIN)[0]
        tail = existing.split(END, 1)[1]
        return head + region + tail
    return existing.rstrip("\n") + "\n\n" + region + "\n"


def main(argv: list[str]) -> int:
    region = render()
    if "--write" not in argv:
        print(region)
        return 0
    text = ARCHITECTURE.read_text(encoding="utf-8")
    ARCHITECTURE.write_text(splice(text, region), encoding="utf-8")
    print(f"wrote the generated region into {ARCHITECTURE}")
    return 0


if __name__ == "__main__":  # pragma: no cover - a CLI
    raise SystemExit(main(sys.argv[1:]))
