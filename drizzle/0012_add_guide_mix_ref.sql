-- media.guide_mix_ref — the GUIDE MIX: both separated stems in ONE 4-channel FLAC (channels 0/1 the
-- instrumental, 2/3 the vocals). When set, the TV plays that one file through a SINGLE media element and
-- splits the channels in WebAudio, giving each pair its own gain.
--
-- WHY. Two stems are two media elements, which is two decoders and two clocks. Two clocks cannot be
-- sample-locked from script: guide-sync.ts can only compare each element's reported `currentTime`, which
-- is the spec's official playback position and does NOT include either element's output latency — so the
-- drift governor converges to "aligned" on a signal that does not describe what the ear hears, and then
-- correctly stops correcting. One file has one playhead, so guide drift becomes unrepresentable.
--
-- A real numbered migration (0012, after 0011_add_lyrics_override_text), NOT an in-place edit of the
-- baseline: drizzle keys replay on the journal `when`, so a rewritten baseline never re-applies to an
-- existing box and the column would be missing at boot the first time a reader selected it (the trap the
-- 0004/0005/0006/0010 headers record, and db.test.ts pins). This replays only on DBs that have not
-- recorded idx:12.
--
-- ADDITIVE AND NULLABLE. A plain `ADD COLUMN`, not the __new_ create-copy-drop-rename idiom, because
-- `media` needs no primary-key change (same shape as 0006/0007/0008/0010/0011). The column is NULLABLE with no
-- default on purpose: null ⇔ "no mix — the row predates the feature, has no vocals stem, or its
-- best-effort encode failed", which guidePath() maps to the legacy two-element path. So every song already
-- in the library keeps today's playback byte-for-byte after the upgrade; the boot-time guide-mix backfill
-- fills them in afterwards from the stems already on disk, without re-separating anything.
ALTER TABLE `media` ADD `guide_mix_ref` text;
